/**
 * The demo customer base — **invented lookalikes, never the real sheet.**
 *
 * This repository is private today and goes public at each audit
 * (`WORKFLOW §8`), so not one name, phone number or contact here belongs to a
 * real Technopanel customer. What is copied is the *shape* of the founder's
 * live sheet: Arabic company names with a few English ones, contractors and
 * factories dominating, Riyadh-heavy with real weight in the East, one
 * contact per company or none, and a rep's own note on roughly half.
 *
 * **Lead source is mapped, not extended** `S17`. The sheet's four values are
 * Google · Sales (Prospect) · Sales (Account) · walk-in, and `S17` fixes the
 * list at six: field visit, direct contact, referral, exhibition, marketing,
 * other. So they map —
 *
 *   Sales (Prospect) → Field visit      the rep went out and found them
 *   Sales (Account)  → Direct contact   an account already in the book
 *   walk-in          → Direct contact   they came to us
 *   Google           → Other            `S17` names no search engine, and
 *                                       Marketing means the marketing TEAM
 *                                       sourced it, which would be a lie
 *
 * — and nothing is added. A seventh lead source is a rule, not a row.
 *
 * **Marketing is absent on purpose and cannot be produced.**
 * `assertLeadSourceSelectable` admits it only for a `can_assign` holder
 * (`lookups.ts:290`), and every `can_assign` holder in `people.ts` is
 * elevated — `verify:schema25` §21 asserts that no live company membership is
 * held by one. Nobody in this dataset can both choose it and keep the company.
 *
 * **Four names are deliberately long** — two Arabic (one quiet), one
 * English, one contact.
 * `S12` gives a company a single name field, so a list's lead cell and a
 * detail heading are exactly where RTL truncation breaks, and nothing else in
 * the base is long enough to find it.
 *
 * **Reach them with `/companies?sort=recent`.** All three are recent, which
 * used to put them on page one because the list defaulted to
 * `desc(created_at)`. It defaults to attention now `D25`, and recent is the
 * calm end of that order — the long Arabic company is `age: 8`, so it sorts
 * near the *back*. That is intended, not a regression: the sort is kept
 * precisely so these stay one URL away. `verify:routes` §20 drives it.
 *
 * **The gap above closed in session 48, the other way round**: rather than
 * making a long name quiet — a clock change that would move every count the
 * suite reads — an already-quiet company (`age: 116`, last logged ~110 days
 * back in `activity.ts`) took a fourth deliberately-long Arabic name. No date moved, no group count moved,
 * and the DEFAULT attention order now carries a long name at the top of GONE
 * QUIET, where a rep actually looks (`WORKFLOW §5`).
 *
 * `region` is never written here: `S15` derives it from the city and the rep
 * is never asked. Country is Saudi unless `country` says otherwise, and a
 * non-Saudi company carries no city and no region at all `S14` `S15`.
 */

import type { PersonKey } from "./people";

/** `company_categories.name_en`. */
export type Category =
  | "Factory"
  | "Contractor"
  | "Advertising"
  | "Real Estate"
  | "Owner"
  | "Consultant"
  | "Station Management"
  | "Workshop"
  | "Personal"
  | "Other";

/** `lead_sources.name_en`, minus Marketing — see the note above. The two
 *  channels session 52 added `S17` reach four recent rows, so the
 *  *where business comes from* chart is drawn with every source a rep can
 *  pick; the pre-rule blanks (age over 45) are untouched by that. */
export type Source =
  | "Field visit"
  | "Direct contact"
  | "Referral"
  | "Exhibition"
  | "Online or WhatsApp"
  | "Consultant or architect"
  | "Other";

