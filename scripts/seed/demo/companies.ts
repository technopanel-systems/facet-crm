  /** ISO 3166-1 alpha-2. Defaults to Saudi Arabia `S14`. */
  country?: string;
  source: Source;
  phone: string;
  /** Days before today the rep registered it. */
  age: number;
  /** Exactly one, or none — what the real sheet looks like `S19`. */
